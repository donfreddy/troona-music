/// Isar-persisted representation of a device audio file.
///
/// [deviceId] mirrors the stable `SongModel.id` provided by the platform
/// MediaStore / MediaLibrary and is used as the diff key during incremental
/// library scans.
@collection
class TrackModel {
  /// Isar auto-increment primary key (assigned on first write).
  int id = 0;

  /// Stable device identifier (MediaStore ID on Android, persistent ID on iOS).
  /// Indexed uniquely so scans can diff the cache in O(1) per track.
  @Index(unique: true)
  late String deviceId;

  /// Absolute file-system path to the audio file.
  late String path;

  /// Content URI used as the audio source for playback.
  late String uri;

  late String title;

  /// The artist tag as written: "Nicki Minaj, Beyoncé".
  late String artist;

  /// The first of [artistIds].
  late int artistId;

  /// Every artist [artist] credits, the first one first, with their ids
  /// in [artistIds]. Set by [link].
  List<String> artistNames = [];

  /// [TrackTags.artistIdFor] of each of [artistNames].
  List<int> artistIds = [];

  late String album;

  /// MediaStore's album id, or the id of the album it was joined into
  /// ([link]).
  late int albumId;
  late String genre;
  late int genreId;

  /// Duration in milliseconds; 0 when the platform returns null.
  late int durationMs;

  late String fileName;
  late int trackNumber;
  late int size;
  late int year;
  String? composer;
  DateTime? dateAdded;
  DateTime? dateModified;

  /// Timestamp of first insertion into the Isar cache.
  ///
  /// Indexed for efficient descending sort in [IsarLibraryDataSource.getRecentTracks].
  /// Set once at scan time and never updated on subsequent scans.
  @Index()
  late DateTime indexedAt;

  /// Absolute path to the JPEG artwork file in the app-cache directory.
  /// Null until artwork has been extracted by [ArtworkExtractor].
  String? artworkPath;

  /// True once [ArtworkExtractor] has looked at this track, whether or not it
  /// found a cover. Without it, files with no embedded artwork were queried
  /// again on every launch.
  bool artworkChecked = false;

  // ---------------------------------------------------------------------------
  // Mapping
  // ---------------------------------------------------------------------------

  /// Creates a [TrackModel] from the platform [SongModel].
  ///
  /// Falls back to the filename (without extension) when [SongModel.title] is
  /// empty, and to sensible English defaults for missing optional fields.
  /// Without an artist tag, the artist comes from an "Artist - Title" name
  /// (see [nameMissingArtist]).
  static TrackModel fromSongModel(SongModel s) =>
      (TrackModel()
          ..deviceId = s.id.toString()
          ..path = s.data
          ..uri = s.uri.orDefault('')
          ..title = s.title.isNotEmpty ? s.title : s.displayNameWOExt
          ..artist = TrackTags.artist(s.artist)
          ..artistId = TrackTags.artistIdFor(TrackTags.artist(s.artist))
          ..album = s.album.orDefault('Unknown Album')
          ..albumId = s.albumId.orDefault()
          ..genre = s.genre.orDefault('Unknown Genre')
          ..genreId = 0
          ..durationMs = s.duration.orDefault()
          ..fileName = s.displayName
          ..trackNumber = s.track.orDefault()
          ..size = s.size
          // The plugin hands the year over as text ("2017").
          ..year = int.tryParse('${s.getMap['year'] ?? ''}') ?? 0
          ..composer = s.composer
          ..dateAdded = (s.getMap['date_added'] as int?).toDateTime()
          ..dateModified = (s.getMap['date_modified'] as int?).toDateTime()
          ..indexedAt = DateTime.now())
        ..nameMissingArtist(s.displayNameWOExt);

  /// Without an artist, reads one from [fileTitle] (the file name without
  /// its extension) when it is "Artist - Title".
  ///
  /// A real title tag is never split: "Song - Live" may be a title. It is
  /// kept, and the file name gives the artist only when its title matches
  /// the tag.
  void nameMissingArtist(String fileTitle) {
    if (!TrackTags.isUnknownArtist(artist)) return;
    final named = TrackTags.fromName(fileTitle);
    if (named == null) return;
    if (title == fileTitle) {
      title = named.title;
    } else if (!_matches(title, named)) {
      return;
    }
    artist = named.artist;
    artistId = TrackTags.artistIdFor(named.artist);
  }

  /// Whether the title tag [tag] is the title [named] read from the file
  /// name, or that title with something after it ("Song - Remastered").
  static bool _matches(String tag, ({String artist, String title}) named) {
    final fromTag = TrackTags.fromName(tag);
    if (fromTag != null &&
        fromTag.artist.toLowerCase() == named.artist.toLowerCase() &&
        fromTag.title.toLowerCase() == named.title.toLowerCase()) {
      return true;
    }
    return tag.trim().toLowerCase().startsWith(named.title.toLowerCase());
  }

  /// Fills in the artists and albums of [tracks], the whole library as
  /// scanned: the artists each song credits ([ArtistCredits]), then the
  /// albums Android split ([AlbumMerge]). [albumId] must still be the one
  /// MediaStore gave.
  static void link(List<TrackModel> tracks) {
    final credits = ArtistCredits.of(tracks.map((t) => t.artist));
    for (final t in tracks) {
      t.artistNames = credits.split(t.artist);
      t.artistIds = [for (final n in t.artistNames) TrackTags.artistIdFor(n)];
      t.artistId = t.artistIds.first;
    }
    final albumIds = AlbumMerge.albumIds([
      for (final t in tracks)
        (albumId: t.albumId, album: t.album, artistIds: t.artistIds),
    ]);
    for (final (i, t) in tracks.indexed) {
      t.albumId = albumIds[i];
    }
  }

  /// Copies onto this stored row everything a scan read for the same file
  /// ([scanned], already [link]ed), keeping what the app added: the cover
  /// and when it was indexed. Returns whether anything changed.
  ///
  /// Every field MediaStore gives is taken, not only the tags: a row an
  /// earlier version stored wrong (no year, a lost size) heals on the next
  /// scan.
  bool refreshFrom(TrackModel scanned) {
    // Rows indexed by earlier versions hold `<unknown>` or "Unknown Artist".
    final scannedArtist = TrackTags.artist(scanned.artist);
    final changed =
        path != scanned.path ||
        uri != scanned.uri ||
        title != scanned.title ||
        artist != scannedArtist ||
        artistId != scanned.artistId ||
        album != scanned.album ||
        albumId != scanned.albumId ||
        genre != scanned.genre ||
        genreId != scanned.genreId ||
        durationMs != scanned.durationMs ||
        fileName != scanned.fileName ||
        trackNumber != scanned.trackNumber ||
        size != scanned.size ||
        year != scanned.year ||
        composer != scanned.composer ||
        dateAdded != scanned.dateAdded ||
        dateModified != scanned.dateModified ||
        !_sameList(artistIds, scanned.artistIds) ||
        !_sameList(artistNames, scanned.artistNames);
    if (!changed) return false;
    path = scanned.path;
    uri = scanned.uri;
    title = scanned.title;
    artist = scannedArtist;
    artistId = scanned.artistId;
    artistNames = List.of(scanned.artistNames);
    artistIds = List.of(scanned.artistIds);
    album = scanned.album;
    albumId = scanned.albumId;
    genre = scanned.genre;
    genreId = scanned.genreId;
    durationMs = scanned.durationMs;
    fileName = scanned.fileName;
    trackNumber = scanned.trackNumber;
    size = scanned.size;
    year = scanned.year;
    composer = scanned.composer;
    dateAdded = scanned.dateAdded;
    dateModified = scanned.dateModified;
    return true;
  }

  static bool _sameList<T>(List<T> a, List<T> b) {
    if (a.length != b.length) return false;
    for (var i = 0; i < a.length; i++) {
      if (a[i] != b[i]) return false;
    }
    return true;
  }

  /// Converts this model to the immutable domain [Track] entity.
  Track toEntity() => Track(
    id: deviceId,
    path: path,
    uri: uri,
    size: size,
    title: title,
    // Rows indexed by earlier versions hold `<unknown>` or "Unknown Artist".
    artist: TrackTags.artist(artist),
    artistId: artistId,
    credits: _credits(),
    album: album,
    albumId: albumId,
    genre: genre,
    genreId: genreId,
    trackNumber: trackNumber,
    durationMs: durationMs,
    fileName: fileName,
    artworkPath: artworkPath,
    year: year,
    composer: composer,
    dateAdded: dateAdded,
    dateModified: dateModified,
  );

  /// [artistNames] with their ids; a row a scan has not [link]ed yet reads
  /// as its one artist.
  List<ArtistCredit>? _credits() {
    if (artistIds.isEmpty || artistIds.length != artistNames.length) {
      return null;
    }
    return [
      for (final (i, id) in artistIds.indexed)
        ArtistCredit(id: id, name: TrackTags.artist(artistNames[i])),
    ];
  }
}
